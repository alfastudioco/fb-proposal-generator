// Minimal .env.local loader for local scratch/dev scripts. Not used by the
// deployed app (Vercel injects env vars itself; `vercel dev` auto-loads
// .env.local natively) -- this exists only so plain `node scripts/foo.js`
// runs can read the same file without adding a dotenv dependency.
const fs = require('fs');
const path = require('path');

function loadEnvLocal() {
  const envPath = path.join(__dirname, '..', '.env.local');
  if (!fs.existsSync(envPath)) return;
  for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim();
    if (!(key in process.env)) process.env[key] = value;
  }
}

loadEnvLocal();
